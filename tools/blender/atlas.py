# 臉的底色（眼睛、嘴、腮紅貼片的背景）：要和頭的頂點色完全一樣，貼片邊緣才看不出來
SKIN = '#ffd8bd'


def uv_of(px, py, size=SIZE):
    """像素（左上原點）→ Blender UV（左下原點）"""
    return px / size, 1 - py / size


def rect_uv(rect, s, t, pad=2, size=SIZE):
    """rect 裡的相對位置 (s, t)（0～1，t = 0 在上緣）→ Blender UV；邊緣內縮 pad 像素，縮圖時不會吃到隔壁格"""
    x, y, w, h = rect
    s = min(max(s, 0.0), 1.0)
    t = min(max(t, 0.0), 1.0)
    return uv_of(x + pad + s * (w - 2 * pad), y + pad + t * (h - 2 * pad), size)
